from hw import display

SHIP_X = 120                  # העמודה שבה יושבת החללית
SHIP_H = 12                   # גובה החללית
MAX_SHIP_Y = 64 - SHIP_H      # 52

BALL = 5                      # גודל הכדור, והוא גם גודל המטאור


def draw_ship(y):
    """חללית בת 12 פיקסלים, מחודדת שמאלה לכיוון הכדור."""
    display.fill_rect(122, y + 2, 6, 8, 1)      # גוף
    display.vline(121, y + 4, 4, 1)             # חרטום
    display.vline(120, y + 5, 2, 1)
    display.hline(125, y, 3, 1)                 # כנפון עליון
    display.hline(125, y + 11, 3, 1)            # כנפון תחתון


def draw_rock(x, y):
    """כדור או מטאור, 5 על 5: שני מלבנים חופפים יוצרים מתומן."""
    display.fill_rect(x + 1, y, 3, 5, 1)
    display.fill_rect(x, y + 1, 5, 3, 1)


def draw_lives(n):
    """n ריבועים קטנים בפינה, ליד הניקוד. בשימוש רק אם הוספתם חיים."""
    for i in range(n):
        display.fill_rect(104 + i * 6, 0, 4, 4, 1)
