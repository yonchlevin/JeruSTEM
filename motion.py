# דברים שכדאי לנסות:
#   - שנו את SPEED ל-1, ל-3 ול-8. מתי התנועה מפסיקה להיראות חלקה?
#   - שנו את הקוד כך שהקו ינוע מלמעלה למטה במקום משמאל לימין.
#   - הציגו את הערך של x כטקסט בפינת המסך תוך כדי תנועה.

from hw import display

LINE_W = 20
SPEED = 2

x = 0

while True:
    display.fill(0)                       # מוחקים
    display.hline(x, 32, LINE_W, 1)       # מציירים
    display.show()                        # מציגים

    x = x + SPEED                         # מקדמים
    if x > 127:
        x = 0
